def T(text):
    return {"type": "text", "text": text}


def TIP(text):
    return {"type": "tip", "text": text}


def LETTERS(*pairs, title=None):
    b = {"type": "letters", "items": [{"ar": a, "bn": n} for a, n in pairs]}
    if title:
        b["title"] = title
    return b


def EX(ref, find, note):
    return {"type": "example", "ref": ref, "words": locate(ref, find), "note": note}


def Q(q, options, answer, explain):
    return {"q": q, "options": options, "answer": answer, "explain": explain}


def lesson(id, title, blocks, quiz):
    return {"id": id, "title": title, "review": DRAFT, "blocks": blocks, "quiz": quiz}


